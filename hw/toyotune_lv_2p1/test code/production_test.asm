                        ; increment counter, loop if not back to 0
                        inc a
                        bne loop1
                        
                        ; invert DDR
                        ld  a, ddr_value
                        xor a, #0ffh
                        st  a, ddr_value
                        
                        ; toggle LED
                        ld  a, $DOUT
                        xor a, #0ffh
                        st  a, $DOUT

                        bra loop2

                        
