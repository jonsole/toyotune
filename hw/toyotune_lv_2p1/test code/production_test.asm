                        ; read IRP, shift to bit 1, check against PORTD.1
                        push a
                        ld  b, $PBCS
                        and b, #20h
                        shr b
                        shr b
                        shr b
                        shr b
                        and a, #02h
                        cmp a, b
                        beq no_irp_error
                        bsr irp_error
