                        bne delay1

                        ; read PORTA, check against test value
                        ld  b, $PORTA
                        cmp a, b
                        beq no_porta_error
                        bsr porta_error                        
no_porta_error:
                        ; read PORTB, check against test value
                        ld  b, $PORTB
                        cmp a, b
                        beq no_portb_error
                        bsr portb_error                        
