                        ; read IS, check against PORTD.0
                        push a
                        ld  b, $PBCS
                        and b, #10h
                        shr b
                        shr b
                        shr b
                        shr b
                        and a, #01h
                        cmp a, b
                        beq no_is_error
                        bsr is_error
