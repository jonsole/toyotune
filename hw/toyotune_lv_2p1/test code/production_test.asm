__RESET:                ; change to mode 2 (external)
                        ld  #02h, $OMODE            
                        di
                                
                        ; .byte stack pointer
                        ld  s, #01BFh               

                        ; initialise UART                        
                        ld  #18h, $SMRC_SIR         ; .byte SMRC cintrol reg to 0001 1000
                                
                        
                        ; initialise DDR value
                        ld  a, #055h
                        st  a, ddr_value

                        ld  #0E3h, $ASR0PL              ; ASR0 pos edge counter value LSB
                        ld  #3Fh,  $TAIT                 ; Timer ASR Control
                                                
                        ; turn LED on
                        ld  #00h, $DOM
                        ld  #00h, $DOUT                        
                        
loop2:                  
                        ; checksum ROM
                        jsr checksum
                        jsr putword

                        ; get DDR value, load into DDRA
                        ld  a, ddr_value                        
                        st  a, $DDRA
                        
                        ; load inverted DDR into DDRB
                        xor a, #0ffh
                        st  a, $DDRB
                        
                        ; reset test value
                        ld  a, #00h                 
loop1:                  
                        ; output test value on output bits of PORTA and PORTB
                        st  a, $PORTA
                        st  a, $PORTB
                        
                        ; output test value on PORTD
                        st  a, $PORTD_ASRIN

                        ; wait a bit for inputs to stabilise                        
                        ld  x, #0ff00h
