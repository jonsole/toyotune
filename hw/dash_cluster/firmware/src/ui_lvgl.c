/* The gauge value readout. Montserrat, like the tick labels, but with tabular
   digits: every digit has the same advance, so a changing reading does not
   shuffle sideways the way a proportional centred label does. Generated by
   tools/gen_font.py - regenerate it, do not edit it. */
LV_FONT_DECLARE(dash_font_value_56);

/* The unit under a gauge's value, in the dial's legend face. */
LV_FONT_DECLARE(dash_font_legend_26);

/* Vertical space between a gauge's value and the unit printed under it. */
#define UI_GAUGE_UNIT_GAP	(6)

/* One LVGL object per element of the current page, rebuilt on a page change
   and only updated in between. Rebuilding every frame would allocate and free
   continuously on a node with no heap to spare. */
#define UI_MAX_ELEMENTS		(8)

/* Enough for the longest formatted value plus its unit - Signal_Format() is
   bounded well under this. */
#define UI_TEXT_MAX		(24)

/* How often a graph advances. A chart is a time series and has to move whether
   or not the reading changed, so it is the one widget that cannot be skipped
   when nothing happens - which makes its cadence a real cost. At 100 points
   this gives ten seconds of history; driving it every 20 ms gave two, and
   redrew five times as often for the privilege. */
#define UI_CHART_PERIOD_MS	(100u)

/* How often a value readout's text is redrawn. The needle moves on every frame;
   the number does not need to. Digits changing sixty times a second cannot be
   read anyway, and redrawing them was the largest cost left in a frame - the
   56 px glyphs plus the face copied out of flash behind them - which put a
   frame over the 16.8 ms scan often enough to miss about one scan in nine. Ten
   updates a second still reads as live. A change of state - a gauge going
   stale, or data arriving - is shown at once, not held for the next tick. */
#define UI_VALUE_PERIOD_MS	(100u)

typedef struct
{
	lv_obj_t *Object;	/* the scale, arc, bar or label itself */
	lv_obj_t *Value;	/* the value text, where the widget has one */
	lv_obj_t *Unit;		/* WIDGET_GAUGE only: the unit, apart from the value */
	lv_obj_t *Label;	/* the signal name */
	lv_obj_t *Needle;	/* WIDGET_GAUGE only: the line that swings */
	int32_t NeedleLen;	/* pixels from the pivot to the tip, fixed at build */
	int32_t NeedleInner;	/* pixels from the pivot to where the needle starts */
	int32_t NeedleCx;	/* pivot, in the scale's own coordinates */
	int32_t NeedleCy;

	/* What was last pushed into LVGL, so an unchanged gauge costs nothing.
	   See the note at the top of UiLvgl_Update(). */
	bool Primed;		/* false until every property has been pushed once */
	uint16_t LastPosition;

	/* WIDGET_GAUGE only: the eased needle position, UI_NEEDLE_Q fractional
	   bits, and the endpoints last drawn - a needle is only re-sent to LVGL
	   when a pixel of it would actually move. */
	uint32_t SmoothQ;
	int32_t LastIx, LastIy, LastTx, LastTy;
	UiState_t LastState;
	const char *LastLabel;
	const char *LastUnit;
	char LastText[UI_TEXT_MAX];

	uint32_t NextChartMs;
	uint32_t NextTextMs;	/* when the value text may next be redrawn */
} UiObject_t;

static lv_obj_t *Screen;
